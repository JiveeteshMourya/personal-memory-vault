import "server-only";
import { betterAuth } from "better-auth";
import { drizzleAdapter } from "better-auth/adapters/drizzle";
import { nextCookies, toNextJsHandler } from "better-auth/next-js";
import { db } from "@/server/lib/db";
import { env } from "@/server/lib/env";

/**
 * The Better Auth server instance. Only `src/server/lib/auth*.ts`, the `require-user` middleware and
 * the auth service may import it or anything from `better-auth`; the rest of the app goes through them.
 */
export const auth = betterAuth({
  secret: env.BETTER_AUTH_SECRET,
  baseURL: env.BETTER_AUTH_URL,
  // Tables live in src/server/models/auth.model.ts, named in the plural (`users`, not the reserved `user`).
  database: drizzleAdapter(db, { provider: "pg", usePlural: true }),
  // Signs the new owner in right after sign-up. Passwords must be 8–128 characters.
  emailAndPassword: { enabled: true },
  // UUID ids, generated by Postgres, like every other table's.
  advanced: { database: { generateId: "uuid" } },
  // Lets Server Actions set and clear the session cookie. Must stay the last plugin.
  plugins: [nextCookies()],
});

/** The `/api/auth/*` route handler. */
export const authHandler = toNextJsHandler(auth);
